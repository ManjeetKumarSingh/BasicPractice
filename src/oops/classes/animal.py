class Animal:
    def __init__(self, name, species, age):
        self.name = name
        self.species = species
        self.age = age

    def speak(self):
        print("The animal speaks")

    def eat(self):
        print("The animal eats")

    def sleep(self):
        print("The animal sleeps")

    def move(self):
        print("The animal moves")
